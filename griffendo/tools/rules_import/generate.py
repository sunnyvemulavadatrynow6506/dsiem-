"""Generate one rule module per eligible rule, the registry index and the rule inventory.

    python3 tools/rules_import/generate.py --elastic DIR --wazuh DIR

Writes src/logplatform/detection/rules/** (replacing previously generated files) and
docs/rules_inventory.json (every inspected rule with its classification, used by the
report and the inventory spreadsheet).  Griffendo-authored chain / behaviour rules and the
v2-v4 catalog rules are generated from griffendo_rules.py and catalog/anomaly_catalog.json.
"""
from __future__ import annotations

import argparse
import json
import pprint
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "src"))

import availability as av  # noqa: E402
import elastic  # noqa: E402
import griffendo_rules  # noqa: E402
import wazuh  # noqa: E402

from logplatform.detection.engine import conditions, schema  # noqa: E402

RULES_DIR = ROOT / "src" / "logplatform" / "detection" / "rules"
GENERATED_MARK = "# Generated by tools/rules_import/generate.py"
FOLDERS = {
    schema.SECURITY.lower(): "security", schema.SYSTEM.lower(): "system", schema.APPLICATION.lower(): "application",
    schema.SYSMON.lower(): "sysmon", schema.DEFENDER.lower(): "defender", schema.FIREWALL.lower(): "firewall",
    schema.POWERSHELL.lower(): "powershell", schema.TASKS.lower(): "taskscheduler", schema.WMI.lower(): "wmi",
}
ELASTIC_ATTRIBUTION = ("Copyright Elasticsearch B.V. and/or licensed to Elasticsearch B.V. under one or more "
                       "contributor license agreements. Licensed under the Elastic License 2.0; you may not use this "
                       "file except in compliance with the Elastic License 2.0.")
COMPLIANCE_PREFIXES = ("pci_dss", "gdpr", "hipaa", "nist_", "tsc_", "gpg13", "windows", "sysmon", "")


def folder_for(channels: list[str]) -> str:
    names = {FOLDERS.get(c.lower(), "other") for c in channels}
    if len(names) == 1:
        return names.pop()
    if "sysmon" in names:
        return "sysmon"
    if "security" in names:
        return "security"
    return sorted(names)[0] if names else "other"


def module_name(rule_id: str) -> str:
    return "rule_" + re.sub(r"[^A-Za-z0-9]", "_", rule_id)


def write_rule(spec: dict, folder: str, header: str) -> str:
    path = RULES_DIR / "windows" / folder
    path.mkdir(parents=True, exist_ok=True)
    top = RULES_DIR / "windows" / "__init__.py"     # a real package: the frozen exe has no namespace packages
    if not top.exists():
        top.write_text('"""Imported and catalog rules, by Windows event source."""\n', encoding="utf-8")
    init = path / "__init__.py"
    if not init.exists():
        init.write_text(f'"""Rules for the {folder} event source (one module per rule)."""\n', encoding="utf-8")
    name = module_name(spec["id"])
    body = pprint.pformat(spec, width=118, sort_dicts=False)
    (path / f"{name}.py").write_text(f'"""{header}"""\n{GENERATED_MARK}\n\nRULE = {body}\n', encoding="utf-8")
    return f"windows.{folder}.{name}"


def write_package(sub: str, spec: dict, header: str) -> str:
    path = RULES_DIR / sub
    path.mkdir(parents=True, exist_ok=True)
    init = path / "__init__.py"
    if not init.exists():
        init.write_text(f'"""{sub} rules (one module per rule)."""\n', encoding="utf-8")
    name = module_name(spec["id"])
    body = pprint.pformat(spec, width=118, sort_dicts=False)
    (path / f"{name}.py").write_text(f'"""{header}"""\n{GENERATED_MARK}\n\nRULE = {body}\n', encoding="utf-8")
    return f"{sub.replace('/', '.')}.{name}"


def _doc(text: str) -> str:
    return text.replace('"""', "'''").replace("\\", "\\\\")


# ------------------------------------------------------------------------------------------- elastic
def until_sources(record: dict) -> tuple[dict | None, str | None]:
    until = record.get("until")
    if not until:
        return None, None
    channels = elastic._channels(record["indexes"])
    survivors, reasons = elastic._step_sources(until["condition"], until["category"], channels, until["by"])
    if not survivors:
        return None, "The sequence's 'until' clause cannot be evaluated locally and was dropped (" + \
            "; ".join(reasons)[:200] + ")."
    return {"condition": until["condition"], "sources": elastic._sources_summary(survivors), "by": until["by"]}, None


def elastic_spec(record: dict) -> dict:
    steps = record["steps"]
    modifications = list(record.get("modifications") or [])
    severity = record["severity"]
    spec = {
        "id": record["griffendo_id"], "name": record["name"], "description": record["description"],
        "category": record["tactic"], "severity": severity, "risk_score": record["risk_score"],
        "confidence": record["confidence"], "kind": record["kind"], "origin": "elastic", "enabled": True,
    }
    if record["kind"] == "sequence":
        spec["steps"] = [{"condition": s["condition"], "sources": s["sources"], "by": s["by"], "runs": s["runs"]}
                         for s in steps]
        spec["maxspan"] = record.get("maxspan") or 3600
        if not record.get("maxspan"):
            modifications.append("The sequence has no maxspan; Griffendo bounds it to 1 hour.")
        until, note = until_sources(record)
        if until:
            spec["until"] = until
        if note:
            modifications.append(note)
    else:
        spec["condition"] = steps[0]["condition"]
        spec["sources"] = steps[0]["sources"]
    for key in ("threshold", "new_terms"):
        if record.get(key):
            spec[key] = record[key]
    used = set()
    for step in steps:
        used |= conditions.fields_used(step["condition"])
    spec.update({
        "required_fields": sorted(used - {"host.os.type"}),
        "mitre": record["mitre"], "investigation": record["investigation"],
        "false_positives": record["false_positives"], "references": record["references"],
        "support": {"status": record["status"], "notes": record.get("reason") or "",
                    "optional_sources": record.get("optional_sources") or [], "witness": record.get("witness")},
        "modifications": modifications,
        "source": {"platform": "Elastic detection-rules", "archive": "windows.zip", "file": record["source_file"],
                   "rule_id": record["source_rule_id"], "type": record["type"], "language": record["language"],
                   "license": record["license"], "attribution": ELASTIC_ATTRIBUTION, "author": record["author"],
                   "updated_date": record["updated_date"], "original_query": record["query"].strip()},
    })
    return spec


# ------------------------------------------------------------------------------------------- wazuh
def wazuh_category(groups: list[str]) -> str:
    useful = [g for g in groups if g and not any(g.startswith(p) for p in COMPLIANCE_PREFIXES[:-1])]
    if useful:
        return useful[-1].replace("_", " ").capitalize()
    return "Windows event"


def wazuh_spec(record: dict) -> dict:
    name = re.sub(r"\s*\$\([^)]*\)", "", record["description"]).strip(" :") or f"Wazuh rule {record['wazuh_id']}"
    severity = record["severity"] or "Informational"
    codes = [int(c) for c in record.get("event_codes") or [] if str(c).isdigit()]
    sources = [{"channel": c, "event_ids": codes} for c in record["channels"]]
    return {
        "id": record["griffendo_id"], "name": name, "description": record["description"],
        "category": wazuh_category(record["groups"]), "severity": severity, "risk_score": record["risk_score"],
        "confidence": "high" if record["status"] in ("fully_supported", "requires_optional_source") else "medium",
        "kind": "wazuh", "origin": "wazuh", "enabled": True, "sources": sources,
        "wazuh": {"wazuh_id": record["wazuh_id"], "level": record["level"], "if_sid": record["if_sid"],
                  "if_group": record["if_group"], "if_matched_sid": record["if_matched_sid"],
                  "if_matched_group": record["if_matched_group"], "frequency": record["frequency"],
                  "timeframe": record["timeframe"], "same_field": record["same_field"],
                  "different_field": record["different_field"], "groups": record["groups"],
                  "if_fts": bool(record.get("if_fts")), "order": record["order"],
                  "condition": record["condition"], "channels": record["channels"],
                  "name_template": record["description"]},
        "required_fields": sorted(conditions.fields_used(record["condition"])),
        "mitre": [{"tactic": "", "technique": t, "name": ""} for t in record["mitre"]],
        "investigation": "", "false_positives": [],
        "support": {"status": record["status"], "notes": record.get("reason") or "",
                    "optional_sources": record.get("optional_sources") or [], "witness": record.get("witness"),
                    "alerting": record["alerting"]},
        "modifications": ["Wazuh <field> OS_Regex patterns translated to equivalent case-insensitive regular "
                          "expressions (or exact values for ^literal$ patterns)."],
        "source": {"platform": "Wazuh ruleset", "archive": "New folder.zip", "file": record["source_file"],
                   "rule_id": record["wazuh_id"], "license": "GPL-2.0 (GNU General Public License v2)",
                   "attribution": record["license_header"]},
    }


def prune_wazuh(records: list[dict]) -> None:
    """A rule whose every ancestor path goes through an excluded rule cannot be reached."""
    by_id = {r["wazuh_id"]: r for r in records}
    changed = True
    while changed:
        changed = False
        for record in records:
            if record["status"] == "unsupported":
                continue
            parents = record["if_sid"] + record["if_matched_sid"]
            if parents and all(by_id.get(p, {}).get("status") == "unsupported" for p in parents) \
                    and not record["if_group"] and not record["if_matched_group"]:
                record["status"] = "unsupported"
                record["reason"] = "Parent rule(s) " + ", ".join(parents) + " cannot be evaluated locally."
                changed = True


# ------------------------------------------------------------------------------------------- catalog
def catalog_specs() -> list[dict]:
    catalog = json.loads((ROOT / "catalog" / "anomaly_catalog.json").read_text(encoding="utf-8"))
    specs = []
    for rule in catalog["rules"]:
        severity = rule["severity"] if rule["severity"] != "Optional" else "Low"
        condition = {"all": [{"field": "event.code", "op": "eq", "values": [str(rule["event_id"])]},
                             {"field": "winlog.channel", "op": "eq", "values": [rule["channel"]], "ci": True}]}
        optional = []
        if rule["channel"] == schema.SYSMON:
            optional.append(av.OPTIONAL_CHANNELS[schema.SYSMON])
        status = "requires_optional_source" if optional else "fully_supported"
        modifications = ["Severity 'Optional' (spreadsheet priority for Sysmon rules) mapped to Low."] \
            if rule["severity"] == "Optional" else []
        specs.append({
            "id": rule["rule_id"], "name": rule["name"], "description": rule.get("notes") or rule["name"],
            "category": rule["category"], "severity": severity, "confidence": "high", "kind": "single",
            "origin": "catalog", "enabled": bool(rule["enabled"]), "condition": condition,
            "sources": [{"channel": rule["channel"], "event_ids": [rule["event_id"]]}],
            "required_fields": ["event.code", "winlog.channel"], "display_fields": rule.get("details") or [],
            "mitre": [], "investigation": "Review the event's details: the rule matches the Event ID alone, so "
                                          "the activity may be legitimate.",
            "false_positives": [rule["false_positives"]] if rule.get("false_positives") else [],
            "support": {"status": status, "notes": rule.get("prerequisite") or "", "optional_sources": optional,
                        "witness": True},
            "modifications": modifications,
            "source": {"platform": "Griffendo anomaly catalog (v2-v4)", "file": "catalog/anomaly_catalog.json",
                       "rule_id": rule["rule_id"], "license": "Griffendo (Soarg)",
                       "spreadsheet_row": rule.get("spreadsheet_row"), "reference": rule.get("reference"),
                       "verification": rule.get("verification")},
        })
    return specs


# ------------------------------------------------------------------------------------------- main
def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--elastic", required=True, type=Path)
    parser.add_argument("--wazuh", required=True, type=Path)
    args = parser.parse_args()
    for path in RULES_DIR.glob("windows"):
        shutil.rmtree(path)
    for sub in ("correlation", "behavior"):
        if (RULES_DIR / sub).exists():
            shutil.rmtree(RULES_DIR / sub)
    modules: list[str] = []
    inventory: list[dict] = []

    elastic_records = elastic.import_all(args.elastic)
    for record in elastic_records:
        entry = {"source": "Elastic", "file": record["source_file"], "source_rule_id": record["source_rule_id"],
                 "name": record["name"], "status": record["status"], "reason": record.get("reason") or "",
                 "type": record["type"], "language": record["language"], "severity": record["severity"],
                 "risk_score": record["risk_score"], "tactic": record["tactic"],
                 "mitre": ", ".join(sorted({m["technique"] for m in record["mitre"] if m["technique"]})),
                 "license": record["license"], "indexes": ", ".join(record["indexes"])}
        if record["status"] != "unsupported":
            spec = elastic_spec(record)
            entry.update(griffendo_id=spec["id"], kind=spec["kind"],
                         channels=", ".join(sorted({s["channel"] for st in record["steps"] for s in st["sources"]})),
                         event_ids=", ".join(str(i) for i in sorted({i for st in record["steps"] for s in st["sources"]
                                                                       for i in s["event_ids"]})),
                         correlation=record["kind"] in ("sequence", "threshold", "new_terms"),
                         optional_sources="; ".join(spec["support"]["optional_sources"]),
                         modifications=" ".join(spec["modifications"]), witness=record.get("witness"),
                         confidence=spec["confidence"])
            channels = sorted({s["channel"] for st in record["steps"] for s in st["sources"]})
            header = (f"{_doc(record['name'])}\n\nSource: Elastic detection-rules, windows/{record['source_file']} "
                      f"(rule_id {record['source_rule_id']}).\nLicense: Elastic License 2.0. {ELASTIC_ATTRIBUTION}\n"
                      f"Status: {record['status']}. Translated from {record['language'].upper()} to Griffendo's "
                      f"condition language; the original query is kept in RULE['source']['original_query'].\n")
            entry["module"] = write_rule(spec, folder_for(channels), header)
            modules.append(entry["module"])
        inventory.append(entry)

    wazuh_records = wazuh.import_all(args.wazuh)
    prune_wazuh(wazuh_records)
    for record in wazuh_records:
        entry = {"source": "Wazuh", "file": record["source_file"], "source_rule_id": record["wazuh_id"],
                 "name": record["description"], "status": record["status"], "reason": record.get("reason") or "",
                 "type": "wazuh", "language": "Wazuh XML (OS_Regex)", "severity": record["severity"] or "(level < 3)",
                 "risk_score": record["risk_score"], "level": record["level"],
                 "mitre": ", ".join(record["mitre"]), "license": "GPL-2.0", "alerting": record["alerting"]}
        if record["status"] != "unsupported":
            spec = wazuh_spec(record)
            entry.update(griffendo_id=spec["id"], kind="wazuh", channels=", ".join(record["channels"]),
                         event_ids=", ".join(record.get("event_codes") or []),
                         correlation=bool(record["frequency"] or record.get("if_fts")),
                         optional_sources="; ".join(spec["support"]["optional_sources"]),
                         modifications=" ".join(spec["modifications"]), witness=record.get("witness"),
                         confidence=spec["confidence"])
            header = (f"{_doc(spec['name'])}\n\nSource: Wazuh ruleset, {record['source_file']} (rule id "
                      f"{record['wazuh_id']}, level {record['level']}).\nLicense: GNU GPL v2. Original notice: "
                      f"{_doc(record['license_header'])}\nStatus: {record['status']}.\n")
            entry["module"] = write_rule(spec, folder_for(record["channels"]) if record["channels"] else "other", header)
            modules.append(entry["module"])
        inventory.append(entry)

    for spec in catalog_specs():
        header = (f"{_doc(spec['name'])}\n\nSource: Griffendo anomaly catalog (v2-v4), rule {spec['id']}: flags every "
                  f"event with this Event ID on this channel.\n")
        module = write_rule(spec, folder_for([spec["sources"][0]["channel"]]), header)
        modules.append(module)
        inventory.append({"source": "Griffendo catalog", "file": "catalog/anomaly_catalog.json",
                          "source_rule_id": spec["id"], "griffendo_id": spec["id"], "name": spec["name"],
                          "status": spec["support"]["status"], "reason": spec["support"]["notes"], "type": "event id",
                          "language": "-", "severity": spec["severity"], "kind": "single",
                          "channels": spec["sources"][0]["channel"],
                          "event_ids": str(spec["sources"][0]["event_ids"][0]), "correlation": False,
                          "module": module, "license": "Griffendo", "witness": True, "confidence": "high"})

    for spec, sub in griffendo_rules.specs():
        header = f"{_doc(spec['name'])}\n\nGriffendo-authored {spec['kind']} rule.\n"
        module = write_package(sub, spec, header)
        modules.append(module)
        inventory.append({"source": "Griffendo", "file": f"tools/rules_import/griffendo_rules.py",
                          "source_rule_id": spec["id"], "griffendo_id": spec["id"], "name": spec["name"],
                          "status": spec["support"]["status"], "reason": spec["support"].get("notes", ""),
                          "type": spec["kind"], "language": "-", "severity": spec["severity"], "kind": spec["kind"],
                          "channels": ", ".join(sorted({s["channel"] for s in spec.get("sources") or []})),
                          "correlation": spec["kind"] in ("chain", "sequence", "behavior"), "module": module,
                          "license": "Griffendo", "witness": True, "confidence": spec.get("confidence", "high"),
                          "mitre": ", ".join(m["technique"] for m in spec.get("mitre") or [])})

    duplicates = sorted({m for m in modules if modules.count(m) > 1})
    if duplicates:
        raise SystemExit(f"duplicate rule modules: {duplicates[:5]}")
    index = RULES_DIR / "index.py"
    index.write_text('"""Registry index: every rule module, one per rule (generated; do not edit by hand)."""\n'
                     f"{GENERATED_MARK}\n\nMODULES = " + pprint.pformat(modules, width=118) + "\n", encoding="utf-8")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "rules_inventory.json").write_text(json.dumps(inventory, indent=1, default=str), encoding="utf-8")
    counts: dict[str, dict[str, int]] = {}
    for entry in inventory:
        counts.setdefault(entry["source"], {}).setdefault(entry["status"], 0)
        counts[entry["source"]][entry["status"]] += 1
    print(json.dumps({"modules": len(modules), "by_source": counts}, indent=1))


if __name__ == "__main__":
    main()
